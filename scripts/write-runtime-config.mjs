/**
 * Writes config.js for static experiences that need Supabase at runtime.
 */
import { writeFileSync, mkdirSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

/** Load KEY=VALUE pairs from .env into process.env when unset. */
function loadDotEnv() {
  const envPath = join(root, '.env');
  if (!existsSync(envPath)) return;
  for (const line of readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq <= 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
}

loadDotEnv();

const supabaseUrl = (
  process.env.VITE_SUPABASE_URL ||
  process.env.SUPABASE_URL ||
  ''
).replace(/\/$/, '');
const supabaseAnonKey =
  process.env.VITE_SUPABASE_ANON_KEY || process.env.SUPABASE_ANON_KEY || '';
const pagesHome =
  process.env.PAGES_HOME ||
  'https://windshifter1.github.io/The-Raconteur-s-Commonplace/';

const source = `/** Generated by scripts/write-runtime-config.mjs — do not edit by hand. */
export default ${JSON.stringify(
  {
    supabaseUrl,
    supabaseAnonKey,
    pagesHome: pagesHome.replace(/\/$/, ''),
  },
  null,
  2,
)};
`;

for (const dir of ['full', 'explore']) {
  const outDir = join(root, dir);
  if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'config.js'), source, 'utf8');
  console.log(`Wrote ${dir}/config.js`, supabaseUrl ? '(with Supabase)' : '(empty credentials)');
}
